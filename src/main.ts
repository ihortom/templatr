import { app, BrowserWindow, Menu, ipcMain, shell, clipboard, nativeTheme } from 'electron';
import fs from 'fs';
import os from 'os';
import path from 'path';
import YAML from 'yaml';


type ThemeSource = 'light' | 'dark';

const pathToSettings = (): string => path.join(os.homedir(), '.templatr', 'settings.yaml');

const loadThemeSource = (): ThemeSource => {
    try {
        const file = fs.readFileSync(pathToSettings(), 'utf8');
        const data = YAML.parse(file);
        if (data?.theme === 'dark') {
            return 'dark';
        }
    }
    catch {
        // no settings yet or unreadable; fall back to light
    }
    return 'light';
};

const saveThemeSource = (source: ThemeSource): void => {
    try {
        const appDir = path.join(os.homedir(), '.templatr');
        if (!fs.existsSync(appDir)) {
            fs.mkdirSync(appDir);
        }
        fs.writeFileSync(pathToSettings(), YAML.stringify({ theme: source }), { encoding: 'utf-8' });
    }
    catch {
        // ignore persistence failures; theme still applies for the session
    }
};


// This allows TypeScript to pick up the magic constants that's auto-generated by Forge's Webpack
// plugin that tells the Electron app where to look for the Webpack-bundled app code 
// (depending on whether you're running in development or production).
declare const MAIN_WINDOW_WEBPACK_ENTRY: string;
declare const ABOUT_WINDOW_WEBPACK_ENTRY: string;
declare const MAIN_WINDOW_PRELOAD_WEBPACK_ENTRY: string;
declare const ABOUT_WINDOW_PRELOAD_WEBPACK_ENTRY: string;
process.env["ELECTRON_DISABLE_SECURITY_WARNINGS"] = 'true';


const createWindow = (): void => {

    let width: number;
    if (process.env.NODE_ENV == 'development') {
        width = 1300;
    }
    else {
        width = 1000;
    }

    // Create the browser window
    const mainWindow = new BrowserWindow({
        title: "Templatr",
        width: width,
        height: 659,
        minWidth: 800,
        minHeight: 200,
        backgroundColor: nativeTheme.shouldUseDarkColors ? "#212529" : "#ffffff",
        resizable: true,
        webPreferences: {
            preload: MAIN_WINDOW_PRELOAD_WEBPACK_ENTRY
        }
    });

    // and load the index.html of the app
    mainWindow.loadURL(MAIN_WINDOW_WEBPACK_ENTRY);

    // Open the DevTools
    if (process.env.NODE_ENV == 'development') {
        mainWindow.webContents.openDevTools();
    }

    // App menu
    const menu = Menu.buildFromTemplate([
        {
            label: 'Application',
            submenu: [
                {
                    label:'About',
                    click() { 
                        openAboutWindow();
                    }
                },
                { type:'separator' },
                {
                    label:'Edit Templates',
                    click() { 
                        shell.openPath(path.join(os.homedir(), '.templatr', 'template.yaml'))
                    }
                },
                {
                    label:'Edit Substitutes List',
                    click() {
                        shell.openPath(path.join(os.homedir(), '.templatr', 'substitutes.yaml'))
                    }
                },
                { type:'separator' },
                {
                    label:'Relaunch App',
                    click() { 
                        app.relaunch({ args: process.argv.slice(1).concat(['--relaunch']) })
                        app.exit(0)
                    }
                },
                { type:'separator' },
                { 
                    label:'Exit', 
                    click() { 
                        app.quit() 
                    } 
                }
            ]
        },
        {
            label: "Edit",
            submenu: [
                { label: "Cut", accelerator: "CmdOrCtrl+X", role: "cut" },
                { label: "Copy", accelerator: "CmdOrCtrl+C", role: "copy" },
                { label: "Paste", accelerator: "CmdOrCtrl+V", role: "paste" },
                { label: "Select All", accelerator: "CmdOrCtrl+A", role: "selectAll" }
            ]
        }
    ]);

    Menu.setApplicationMenu(menu);
};

let aboutWindow: BrowserWindow = null;
  
const openAboutWindow = ():void => {

    if (aboutWindow) {
        aboutWindow.focus();
        return;
    }

    let width: number;
    if (process.env.NODE_ENV == 'development') {
        width = 1000;
    }
    else {
        width = 360;
    }

    // Create the browser window
    aboutWindow = new BrowserWindow({
        height: 370,
        resizable: false,
        width: width,
        title: 'About Templatr',
        minimizable: false,
        fullscreenable: false,
        webPreferences: {
            preload: ABOUT_WINDOW_PRELOAD_WEBPACK_ENTRY
        }
    });

    aboutWindow.loadURL(ABOUT_WINDOW_WEBPACK_ENTRY);

    // Open the DevTools
    if (process.env.NODE_ENV == 'development') {
        aboutWindow.webContents.openDevTools();
    }

    aboutWindow.on('closed', function() {
        aboutWindow = null;
    });
};

// This method will be called when Electron has finished
// initialization and is ready to create browser windows.
// Some APIs can only be used after this event occurs.
app.on('ready', () => {
    nativeTheme.themeSource = loadThemeSource();
    createWindow();
});

// Quit when all windows are closed, except on macOS. There, it's common
// for applications and their menu bar to stay active until the user quits
// explicitly with Cmd + Q.
app.on('window-all-closed', () => {
    if (process.platform !== 'darwin') {
        app.quit();
    }
});

app.on('activate', () => {
    // On OS X it's common to re-create a window in the app when the
    // dock icon is clicked and there are no other windows open.
    if (BrowserWindow.getAllWindows().length === 0) {
        createWindow();
    }
});


